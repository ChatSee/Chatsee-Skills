"""Load the agent's config from a file, so the skills work without a special shell.

A developer should be able to open their editor and run Claude Code — not remember a chain of
`set -a && source … && set +a && claude`. That chain also means the config depends on *how the
process was launched*, which is not something a skill can rely on.

So: real environment variables always win, and anything still missing is filled in from a file.

**Environment wins, always.** This is not a preference — loading a file over an already-set
variable is the bug that used to make a query about a brand-new agent return a different
agent's 151 incidents (VALIDATION.md F1). A caller who exported config gets exactly what they
exported; the file only supplies what is absent.

Sources, highest precedence first:
  1. the real environment
  2. `$CHATSEE_ENV_FILE`, or `.env` in the project root (the directory holding `.claude/`)
  3. `~/.config/chatsee/agent.env` — machine-wide, shared by every project on this machine

Source 3 exists for secrets that are yours rather than the project's — an `ANTHROPIC_API_KEY`
for the agents you build to test against, say. Putting one there means every test agent in every
repo can use it, while it stays out of the shell (and so out of anything that reads the shell's
environment, like Claude Code's own billing).

⚠️ **Source 3 may not identify an agent.** `CHATSEE_AGENT_ID`, `CHATSEE_TENANT_ID`,
`CHATSEE_MCP_KEY` and `CHATSEE_AGENT` are refused from the machine-wide file, with a message
saying so. A global default for *which agent this is* is F1 again one level up: a project with
no `.env` would silently read and write another agent's data. Machine-wide holds what is true
of the machine; the project holds what is true of the agent.

Missing files are not an error: the variables may legitimately come from the real environment,
and the caller gets the usual "set CHATSEE_… " message if they don't.
"""

from __future__ import annotations

import os
import sys

# Identity — never accepted from the machine-wide file. See the module docstring.
AGENT_SCOPED = frozenset(
    {"CHATSEE_AGENT_ID", "CHATSEE_TENANT_ID", "CHATSEE_MCP_KEY", "CHATSEE_AGENT"}
)

_loaded_from: list[str] = []
_done = False


def _project_root() -> str | None:
    """Walk up from this file looking for the directory that holds `.claude/`."""
    d = os.path.dirname(os.path.abspath(__file__))
    while True:
        if os.path.isdir(os.path.join(d, ".claude")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            return None
        d = parent


def user_config_path() -> str:
    """The machine-wide config file. Honours XDG_CONFIG_HOME, else `~/.config`."""
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.join(os.path.expanduser("~"), ".config")
    return os.path.join(base, "chatsee", "agent.env")


def _parse(path: str) -> dict[str, str]:
    """Minimal `KEY=value` reader: no interpolation, no `export`, no multi-line values.

    Deliberately not a full dotenv implementation — the files this reads are generated by
    onboarding or copied from `.env.example`, and quietly mis-parsing a credential is worse
    than not supporting an exotic syntax.
    """
    out: dict[str, str] = {}
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            key = key.strip()
            if not key:
                continue
            value = value.strip()
            # A quoted value ends at its closing quote; anything after it is a comment.
            # Unquoted, a ` #` starts one. Without this, `.env.example`'s
            #   CHATSEE_AGENT="<Your Agent Name>"   # QUOTE it — names contain spaces
            # parsed as the placeholder AND the comment, and the agent name printed back to
            # the developer was the whole line. A wrong agent name is not cosmetic here: it is
            # what skills 3 and 4 scope their questions by.
            # `startswith`, not `value[:1] in "\"'"` — the empty string is a substring of
            # everything, so that form said "quoted" for a blank value and then indexed it.
            if value.startswith(('"', "'")):
                quote = value[0]
                close = value.find(quote, 1)
                value = value[1:close] if close != -1 else value[1:]
            else:
                cut = value.find(" #")
                if cut != -1:
                    value = value[:cut].rstrip()
            out[key] = value
    return out


def resolve(path: str) -> str:
    """Make a config-supplied path absolute, relative to the PROJECT ROOT, not `os.getcwd()`.

    A path written in `.env` means "relative to the project", which is what the person editing
    the file intends. Resolving against the working directory instead would make the same config
    work or fail depending on where the command happened to be run from.
    """
    if os.path.isabs(path):
        return path
    root = _project_root()
    return os.path.join(root, path) if root else os.path.abspath(path)


def _apply(path: str, *, allow_agent_scoped: bool) -> list[str]:
    """Fill absent variables from `path`. Returns the names actually set."""
    try:
        values = _parse(path)
    except OSError as e:
        print(f"warning: could not read {path}: {e}", file=sys.stderr)
        return []

    filled = []
    for k, v in values.items():
        if k in os.environ or v == "":
            continue
        if not allow_agent_scoped and k in AGENT_SCOPED:
            print(
                f"warning: ignoring {k} from {path} — it identifies one agent, and a "
                "machine-wide default would point other projects at it. Put it in that "
                "project's .env instead.",
                file=sys.stderr,
            )
            continue
        os.environ[k] = v
        filled.append(k)
    return filled


def load(announce: bool = True) -> str | None:
    """Fill in absent config from the project file, then the machine-wide one.

    Returns the project file used (or the machine-wide one if that was the only source), for
    callers that report where config came from. Idempotent — safe to call from every entry
    point. `announce` prints one line to stderr naming the source and agent, because "which
    agent am I actually pointed at" being invisible is precisely how F1 happened; stdout is
    never touched.
    """
    global _done, _loaded_from
    if _done:
        return _loaded_from[0] if _loaded_from else None
    _done = True
    _loaded_from = []

    project = os.environ.get("CHATSEE_ENV_FILE")
    if not project:
        root = _project_root()
        project = os.path.join(root, ".env") if root else None

    filled: list[str] = []
    if project and os.path.isfile(project):
        got = _apply(project, allow_agent_scoped=True)
        if got:
            _loaded_from.append(project)
            filled += got

    user = user_config_path()
    if os.path.isfile(user):
        got = _apply(user, allow_agent_scoped=False)
        if got:
            _loaded_from.append(user)
            filled += got

    if announce and filled:
        where = " + ".join(os.path.basename(p) for p in _loaded_from)
        agent = os.environ.get("CHATSEE_AGENT", "?")
        print(f"[config] {where} → agent {agent!r}", file=sys.stderr)
    return _loaded_from[0] if _loaded_from else None
