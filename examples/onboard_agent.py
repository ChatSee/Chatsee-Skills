#!/usr/bin/env python3
"""Onboard a brand-new ChatSee agent and write its config out as an env file.

This is step 0 of the enterprise path: a customer creates an agent and gets the identifiers
their code needs. Every skill then runs from the env file this produces — no ids, keys, or
URLs are hardcoded anywhere. See RUN.md for the full command list.

    ./.venv/bin/python examples/onboard_agent.py --name "My Agent" --out .env.myagent
    set -a && source .env.myagent && set +a
    ./.venv/bin/python examples/marketing_agent.py

Auth: pass --token '<dashboard bearer>', or let this import the login helper from
`register_agent_demo.py` (gitignored — it holds the credentials, which is why they are not
duplicated here).

The generated env file contains a live MCP key, so it is written 0600 and matched by
.gitignore's `.env.*` rule. Never commit it.
"""

import argparse
import json
import os
import stat
import sys

import httpx
from _common import api_base, env_alias, get_token


def main() -> None:
    p = argparse.ArgumentParser(description="Create a ChatSee agent and emit its env file.")
    p.add_argument("--name", required=True, help="Agent name (unique per tenant)")
    p.add_argument("--out", default=None, help="env file to write (default .env.<slug>)")
    p.add_argument("--type", default="InteractionAgent")
    p.add_argument("--subtype", default="CustomAgent")
    p.add_argument("--token", default=None)
    args = p.parse_args()

    slug = "".join(ch if ch.isalnum() else "_" for ch in args.name).strip("_").lower()
    out = args.out or f".env.{slug}"

    base, alias = api_base(), env_alias()
    # The generated env file must carry the MCP endpoint, and the server does not reliably
    # return one (VALIDATION.md P2) — so it has to come from config, not from a default.
    mcp_url = os.environ.get("CHATSEE_MCP_URL")
    if not mcp_url:
        sys.exit("set CHATSEE_MCP_URL — it is written into the generated env file")
    token = get_token(args.token, base)
    print("[auth] ok")

    with httpx.Client(base_url=base, timeout=120.0, verify=False) as client:
        r = client.post(
            "/v1/agents/register_agent",
            headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
            json={"agent_name": args.name, "agent_type": args.type, "agent_subtype": args.subtype},
        )
        try:
            data = r.json()
        except ValueError:
            sys.exit(f"register_agent → HTTP {r.status_code}: {r.text[:300]}")
        if r.status_code != 200:
            sys.exit(f"register_agent → HTTP {r.status_code}: {json.dumps(data)[:400]}")

    agent_id, tenant_id = data.get("agent_id"), data.get("tenant_id")
    mcp_key = data.get("mcp_api_key")
    if not (agent_id and tenant_id and mcp_key):
        sys.exit(f"register_agent returned an incomplete payload: {sorted(data)}")

    print(f"[register] {args.name!r} → agent_id={agent_id}")
    # The server may answer with the alias ("demo") or the full URL — both are correct and
    # mean the same environment. Only warn when it genuinely points somewhere else, which is
    # the P1 failure mode (it used to return the literal string "dev" for a demo agent).
    said = (data.get("api_base_url") or "").rstrip("/")
    if said and said != alias and said != base:
        print(
            f"  note: server said api_base_url={said!r}, which is neither {alias!r} nor "
            f"{base} — using {alias!r}. Following the response verbatim would send this "
            "agent's telemetry to the wrong environment (VALIDATION.md P1).",
            file=sys.stderr,
        )
    if not data.get("mcp_server_url"):
        print(f"  note: server returned no mcp_server_url; using {mcp_url}", file=sys.stderr)

    body = f"""# Generated by examples/onboard_agent.py — contains a LIVE key, never commit.
# Agent: {args.name}
CHATSEE_MCP_URL={mcp_url}
CHATSEE_API_BASE={base}
CHATSEE_MCP_KEY={mcp_key}
CHATSEE_AGENT="{args.name}"
CHATSEE_MCP_TIMEOUT=300

CHATSEE_AGENT_ID={agent_id}
CHATSEE_TENANT_ID={tenant_id}
CHATSEE_ENV={alias}
"""
    with open(out, "w", encoding="utf-8") as f:
        f.write(body)
    os.chmod(out, stat.S_IRUSR | stat.S_IWUSR)  # 0600 — it holds a live key

    print(f"[write] {out} (mode 0600)")
    print(
        f"\nNext: put {os.path.basename(out)} at your project root (the skills read it),\n"
        "gitignore it — it holds a live key — then open Claude Code there and ask it to\n"
        "instrument your agent."
    )


if __name__ == "__main__":
    main()
